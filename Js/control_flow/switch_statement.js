let dayNumber = 6;

switch (dayNumber) {
    case 1:
        console.log("Monday Day");
        break;
    case 2:
        console.log("Tuesday Day");
        break;
    case 3:
        console.log("Wednesday Day");
        break;
    case 4:
        console.log("Thursday Day");
        break;
    case 5:
        console.log("Friday Day");
        break;
    default:
        console.log("Weekend or Invalid Day");
        break;
}

